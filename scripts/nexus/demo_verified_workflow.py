"""Safe offline end-to-end demonstration for AegisForge Nexus.

Install at: scripts/nexus/demo_verified_workflow.py

A deterministic, OFFLINE fixture plan is submitted to the real Nexus Planner,
Orchestrator, Executor, Verifier, and EvidenceTrail contracts. It is not
NVIDIA Nemotron output and never calls Nebius.

--execute explicitly permits one trusted, tightly scoped file-writing tool
inside a temporary directory and a test-running tool over static bundled
fixture code. The verifier separately rechecks fixture hashes and re-runs the
trusted tests. The temporary workspace is NOT an OS security sandbox.

No arbitrary shell commands, code generated by a model, external URLs,
or caller-supplied file paths are executed. --save-evidence exports only
sanitized audit metadata and a chained JSONL journal.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
from typing import Any, Mapping, Sequence

from aegisforge.nexus.evidence import verify_jsonl
from aegisforge.nexus.executor import NexusExecutor, RegisteredTool, ToolResult
from aegisforge.nexus.nebius_client import NebiusReply
from aegisforge.nexus.orchestrator import NexusOrchestrator
from aegisforge.nexus.planner import NexusPlanner
from aegisforge.nexus.verifier import EvidenceExpectation, IndependentCheck

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_NAME = "bounded_math.py"
TEST_NAME = "test_bounded_math.py"

# Trusted demonstration fixtures, deliberately NOT taken from LLM responses.
SOURCE_CODE = '''"""Pure, minimal math utility for a local Nexus demonstration."""\n\ndef clamp(value: int, low: int, high: int) -> int:\n    """Return value within the inclusive [low, high] range."""\n    if low > high:\n        raise ValueError("low cannot exceed high")\n    return max(low, min(value, high))\n'''
TEST_CODE = '''"""Offline smoke checks over a statically defined fixture."""\nfrom pathlib import Path\nimport runpy\n\nclamp = runpy.run_path(str(Path(__file__).with_name("bounded_math.py")))["clamp"]\nassert clamp(4, 1, 9) == 4\nassert clamp(-4, 1, 9) == 1\nassert clamp(14, 1, 9) == 9\nassert clamp(5, 5, 5) == 5\nassert clamp(0, -5, 5) == 0\ntry:\n    clamp(4, 5, 1)\nexcept ValueError:\n    pass\nelse:\n    raise AssertionError("invalid bounds must raise ValueError")\nprint("PASS: 6 static tests")\n'''
TEST_SUCCESS_MARKER = "PASS: 6 static tests"


def _sha256(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _verify_exact_fixture(workspace: Path) -> bool:
    """Read actual on-disk bytes, not a tool's self-reported evidence."""
    for name, expected in ((SOURCE_NAME, SOURCE_CODE), (TEST_NAME, TEST_CODE)):
        path = workspace / name
        if not path.is_file() or path.is_symlink():
            return False
        if hashlib.sha256(path.read_bytes()).hexdigest() != _sha256(expected):
            return False
    return True


def _run_static_tests(workspace: Path) -> bool:
    """Execute only the vetted fixed test fixture, never model/user code."""
    if not _verify_exact_fixture(workspace):
        return False
    # In particular, don't propagate cloud credentials to a child interpreter.
    environment = {key: os.environ[key] for key in
                   ("SystemRoot", "SYSTEMROOT", "WINDIR", "windir", "PATH", "PATHEXT", "TEMP", "TMP")
                   if key in os.environ}
    environment.update({"PYTHONDONTWRITEBYTECODE": "1", "PYTHONIOENCODING": "utf-8"})
    result = subprocess.run(
        [sys.executable, "-I", "-B", str(workspace / TEST_NAME)],
        cwd=workspace, env=environment, capture_output=True,
        text=True, timeout=10, check=False,
    )
    return result.returncode == 0 and result.stdout.strip() == TEST_SUCCESS_MARKER


class _FixedOfflinePlannerClient:
    """Produces a *synthetic* plan for local testing; never calls an API."""

    def chat(self, messages: Sequence[Mapping[str, Any]], *,
             max_tokens: int = 512, temperature: float | None = 0.2) -> NebiusReply:
        submitted = json.loads(messages[-1]["content"])
        required_tools = {"nexus.demo.write", "nexus.demo.tests"}
        if not required_tools.issubset(submitted.get("allowed_tools", {})):
            raise ValueError("Demo tools were not explicitly registered")
        if int(submitted["max_steps"]) < 4:
            raise ValueError("Demo requires four steps")
        fixture = {
            "goal": "Create and independently verify a local clamp() Python fixture",
            "steps": [
                {"id": "s1", "kind": "reason", "title": "Approve fixture scope",
                 "description": "Review vetted local code; do not run LLM-generated code",
                 "tool": None, "depends_on": [],
                 "success_criteria": "Host documents its trust and scope assumptions"},
                {"id": "s2", "kind": "tool", "title": "Write temporary fixture",
                 "description": "Write only two predefined files inside an isolated temporary workspace",
                 "tool": "nexus.demo.write", "depends_on": ["s1"],
                 "success_criteria": "File bytes match pinned SHA-256 digests"},
                {"id": "s3", "kind": "tool", "title": "Execute static tests",
                 "description": "Run six fixed tests against the pinned fixture",
                 "tool": "nexus.demo.tests", "depends_on": ["s2"],
                 "success_criteria": "Local test interpreter exits successfully"},
                {"id": "s4", "kind": "verify", "title": "Independently verify artifacts",
                 "description": "Read hashes and independently rerun the static fixture tests",
                 "tool": None, "depends_on": ["s3"],
                 "success_criteria": "Independent checks cover both tool steps and final verification"},
            ],
            "assumptions": ["Fixtures are static and vetted; temporary files are discarded"],
            "risks": ["A temporary directory does not provide an OS sandbox"],
        }
        return NebiusReply(
            content=json.dumps(fixture, ensure_ascii=False),
            model="local-fixture-not-nemotron", request_id="offline-demo-fixture",
            finish_reason="stop", usage={"total_tokens": 0},
        )


def _build_orchestrator(workspace: Path) -> NexusOrchestrator:
    """Bind two allowlisted host tools; no arbitrary argument surface."""
    def write_handler(arguments: Mapping[str, Any]) -> ToolResult:
        if arguments:
            raise ValueError("No arguments are accepted")
        (workspace / SOURCE_NAME).write_text(SOURCE_CODE, encoding="utf-8", newline="\n")
        (workspace / TEST_NAME).write_text(TEST_CODE, encoding="utf-8", newline="\n")
        return ToolResult(True, "Two pinned fixture files written", {
            "source_sha256": _sha256(SOURCE_CODE),
            "test_sha256": _sha256(TEST_CODE),
        })

    def tests_handler(arguments: Mapping[str, Any]) -> ToolResult:
        if arguments:
            raise ValueError("No arguments are accepted")
        passed = _run_static_tests(workspace)
        return ToolResult(passed, "Static suite passed" if passed else "Static suite failed", {
            "test_suite": "6-static-cases",
            "exit_state": "pass" if passed else "fail",
        })

    registry = {
        "nexus.demo.write": RegisteredTool(
            id="nexus.demo.write", description="Write exactly two trusted files into a temporary directory",
            handler=write_handler, mutating=True,
        ),
        "nexus.demo.tests": RegisteredTool(
            id="nexus.demo.tests", description="Execute six trusted tests without modifying fixture source",
            handler=tests_handler, mutating=False,
        ),
    }
    planner = NexusPlanner(_FixedOfflinePlannerClient(), max_steps=4, max_tokens=2500)
    return NexusOrchestrator(planner, NexusExecutor(registry))


def run_demo(*, execute: bool = False, save_evidence: bool = False,
             evidence_root: Path | None = None) -> dict[str, Any]:
    """Run a preview or one explicitly authorized offline fixture demonstration."""
    with tempfile.TemporaryDirectory(prefix="aegisforge-nexus-fixture-") as temp_dir:
        workspace = Path(temp_dir)
        orchestrator = _build_orchestrator(workspace)
        prepared = orchestrator.prepare(
            "Demonstrate controlled Python utility creation with genuine independent tests",
            constraints=("Static offline fixture only", "No cloud inference", "Scope all writes to temp"),
        )
        attestations = {"s1": "Vetted fixture only; temporary workspace", 
                        "s4": "Host requests independent read-only verification"}
        preview = orchestrator.preview(prepared, manual_evidence=attestations)
        if not execute:
            return {
                "mode": "preview", "live_inference": False,
                "planner_model": prepared.plan.model,
                "plan_steps": len(prepared.plan.steps),
                "preview_status": preview.status,
                "tools_invoked": preview.tools_invoked,
                "files_created": False,
                "note": "To execute static local fixtures, rerun with --execute; no Nebius call is used.",
            }

        checks = [
            IndependentCheck(
                id="fixture_hashes", step_id="s2", description="Re-read pinned artifact SHA-256 digests",
                handler=lambda step, record: _verify_exact_fixture(workspace),
                evidence_ref="local-static-fixture-hashes",
            ),
            IndependentCheck(
                id="repeat_tests", step_id="s3", description="Independently rerun fixed test suite",
                handler=lambda step, record: _run_static_tests(workspace),
                evidence_ref="local-static-test-rerun",
            ),
            IndependentCheck(
                id="final_check", step_id="s4", description="Recheck artifact digests and test suite",
                handler=lambda step, record: _verify_exact_fixture(workspace) and _run_static_tests(workspace),
                evidence_ref="local-final-crosscheck",
            ),
        ]
        outcome = orchestrator.run(
            prepared, execute_tools=True, approved_mutations=frozenset({"s2"}),
            manual_evidence=attestations,
            expectations=[
                EvidenceExpectation("s2", "source_sha256", _sha256(SOURCE_CODE)),
                EvidenceExpectation("s2", "test_sha256", _sha256(TEST_CODE)),
                EvidenceExpectation("s3", "exit_state", "pass"),
            ],
            independent_checks=checks,
        )
        summary: dict[str, Any] = {
            "mode": "offline_fixture", "live_inference": False,
            "planner_model": prepared.plan.model,
            "plan_steps": len(outcome.plan.steps),
            "preview_status": preview.status,
            "execution_status": outcome.execution.status,
            "verification_status": outcome.verification.status,
            "tools_invoked": outcome.execution.tools_invoked,
            "independent_checks_run": outcome.verification.independent_checks_run,
            "independent_checks_passed": outcome.verification.independent_checks_passed,
            "audit_events": len(outcome.evidence.events),
            "audit_sha256": outcome.evidence.final_sha256,
            "temporary_workspace_removed_on_exit": True,
            "source_sha256": _sha256(SOURCE_CODE),
        }
        if save_evidence:
            target = evidence_root if evidence_root is not None else REPO_ROOT / "evidence" / "nexus"
            target.mkdir(parents=True, exist_ok=True)
            audit = target / f"demo_verified_{outcome.evidence.run_id}.jsonl"
            report = target / f"demo_verified_{outcome.evidence.run_id}.json"
            # Create-only writes to avoid overwriting or altering earlier AWS/Nebius evidence.
            outcome.evidence.save_jsonl(audit)
            try:
                with report.open("x", encoding="utf-8") as file:
                    json.dump(summary, file, indent=2, ensure_ascii=False)
            except Exception:
                audit.unlink(missing_ok=True)
                raise
            # Independently validate serialized journal's chain after writing.
            verify_jsonl(audit)
            summary["summary_path"] = str(report)
            summary["audit_path"] = str(audit)
        return summary


def main() -> int:
    parser = argparse.ArgumentParser(description="Offline Nexus end-to-end demo (no Nebius charges)")
    parser.add_argument("--execute", action="store_true", help="Permit only the pinned temp-file write and static tests")
    parser.add_argument("--save-evidence", action="store_true", help="Export sanitized JSON and integrity-checked JSONL")
    args = parser.parse_args()
    if args.save_evidence and not args.execute:
        parser.error("--save-evidence requires --execute")
    try:
        summary = run_demo(execute=args.execute, save_evidence=args.save_evidence)
        print(json.dumps(summary, ensure_ascii=False, indent=2))
        if args.execute and summary["verification_status"] != "verified":
            print("ERROR: final verification is not verified", file=sys.stderr)
            return 1
        return 0
    except Exception as exc:
        # Don't print exception bodies: paths/env/credentials can leak in some errors.
        print(f"ERROR: demo could not finish ({type(exc).__name__}); review local logs", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
